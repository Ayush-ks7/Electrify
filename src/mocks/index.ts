// Generate 30 days of consumption points for CONS-7821
export const generateConsumerHistory = (consumerId: string): ConsumptionDataPoint[] => {
  const points: ConsumptionDataPoint[] = [];
  const now = new Date('2026-10-03T12:00:00Z');
  
  for (let i = 29; i >= 0; i--) {
    const d = new Date(now.getTime() - i * 24 * 60 * 60 * 1000);
    const dateStr = d.toISOString().split('T')[0];
    const label = `${d.toLocaleString('default', { month: 'short' })} ${d.getDate()}`;
    
    // Baseline is steady ~310 with slight weekend dips
    const dayOfWeek = d.getDay();
    const isWeekend = dayOfWeek === 0 || dayOfWeek === 6;
    const base = isWeekend ? 260 : 315;
    const baseline = Math.round(base + (Math.sin(i) * 15));
    const peerAvg = Math.round(base - 10 + (Math.cos(i) * 12));
    
    let actual = baseline + Math.round((Math.sin(i * 1.5) * 18));
    let isAnomaly = false;

    // Last 9 days have severe drop for CONS-7821 (Suspected Theft / unmetered bypass)
    if (consumerId === 'CONS-7821' && i < 9) {
      actual = Math.round(baseline * 0.58 + (Math.sin(i) * 8));
      isAnomaly = true;
    } else if (consumerId === 'CONS-4092' && i < 5) {
      // Meter fault zero readings
      actual = i === 4 ? 40 : 0;
      isAnomaly = true;
    } else if (consumerId === 'CONS-1108' && i < 14) {
      // Comm issue intermittent missing
      actual = i % 2 === 0 ? Math.round(baseline * 0.2) : baseline;
      isAnomaly = true;
    }

    points.push({
      timestamp: dateStr,
      label,
      actual,
      baseline,
      peerAverage: peerAvg,
      isAnomaly,
    });
  }
  return points;
};

// 24H consumption breakdown
export const generate24HourProfile = (consumerId: string): ConsumptionDataPoint[] => {
  const points: ConsumptionDataPoint[] = [];
  for (let h = 0; h < 24; h++) {
    const hourLabel = `${h.toString().padStart(2, '0')}:00`;
    const isNight = h >= 0 && h <= 5;
    const isPeak = h >= 9 && h <= 17;
    
    let baseline = isNight ? 8.2 : isPeak ? 24.5 : 14.0;
    let peerAverage = isNight ? 7.8 : isPeak ? 23.0 : 13.5;
    let actual = baseline;

    if (consumerId === 'CONS-7821') {
      // Dramatic unmetered drop during daytime, but abnormal night spike
      if (isNight) {
        actual = baseline * 2.8; // nighttime shift
      } else if (isPeak) {
        actual = baseline * 0.45; // daytime bypass
      } else {
        actual = baseline * 0.6;
      }
    } else {
      actual = baseline + (Math.sin(h) * 1.5);
    }

    points.push({
      timestamp: hourLabel,
      label: hourLabel,
      actual: Number(actual.toFixed(1)),
      baseline: Number(baseline.toFixed(1)),
      peerAverage: Number(peerAverage.toFixed(1)),
      isAnomaly: consumerId === 'CONS-7821' && (isNight || isPeak),
    });
  }
  return points;
};

